import type { Recipe, RecipeLine } from "../types";
import { INGREDIENTS } from "./ingredients";

/* Small helpers so the data reads like a recipe card. Weights are what you buy. */
const g = (id: string, grams: number, note?: string): RecipeLine => ({ id, g: grams, note });
const ml = (id: string, millilitres: number, note?: string): RecipeLine => ({
  id,
  g: millilitres * (INGREDIENTS[id]?.density ?? 1),
  note,
});
const tbsp = (id: string, n: number, note?: string) => ml(id, n * 15, note);
const tsp = (id: string, n: number, note?: string): RecipeLine => ({
  id,
  g: n * (INGREDIENTS[id]?.tsp ?? 5),
  note,
});
/** Frying oil: you buy `millilitres`, but only `eatenMl` ends up in the food. */
const fry = (millilitres: number, eatenMl: number, note: string): RecipeLine => ({
  id: "oil",
  g: millilitres * 0.92,
  eat: eatenMl * 0.92,
  note,
});

